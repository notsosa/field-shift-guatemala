/** Texto traducido con variables {nombre}; cae al inglés y, si no existe, devuelve la clave. */
export function t(lang, key, vars = {}) {
  const s = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export const locale = (lang) => (lang === 'es' ? 'es-GT' : 'en-US');

export function fmtNumber(lang, x, digits = 0) {
  return new Intl.NumberFormat(locale(lang), { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(x);
}

/** Con signo explícito: +1.2 / −1.2 (signo menos tipográfico) / 0.0. */
export function fmtSigned(lang, x, digits = 0) {
  const r = Number(x.toFixed(digits));
  const s = fmtNumber(lang, Math.abs(r), digits);
  return r > 0 ? `+${s}` : r < 0 ? `−${s}` : s;
}

// Cómo se muestra cada objetivo: escala a unidades legibles, decimales, sentido de "mejor"
// y banda de "casi igual" (en unidades del objetivo).
export const TARGET_META = {
  waterIndex: { scale: 100, digits: 1, absUnit: '%', diffUnit: 'unitPts', higherIsBetter: true, same: 0.005 },
  ksFlowerMain: { scale: 1, digits: 3, absUnit: '', diffUnit: null, higherIsBetter: true, same: 0.005 },
  bareFrac: { scale: 214, digits: 1, absUnit: 'unitDays', diffUnit: 'unitDays', higherIsBetter: false, same: 0.5 / 214 },
};

const unit = (lang, u) => (!u ? '' : u === '%' ? '%' : ` ${t(lang, u)}`);

/** Valor absoluto: 92.5% · 0.950 · 25.1 days. */
export function fmtAbs(lang, targetId, v) {
  const m = TARGET_META[targetId];
  return `${fmtNumber(lang, v * m.scale, m.digits)}${unit(lang, m.absUnit)}`;
}

/** Diferencia con signo: +3.2 pts · +0.012 · −4.1 days. */
export function fmtDiff(lang, targetId, d, digits = TARGET_META[targetId].digits) {
  const m = TARGET_META[targetId];
  return `${fmtSigned(lang, d * m.scale, digits)}${unit(lang, m.diffUnit)}`;
}

/** Error típico: ±4.4 pts · ±0.042 · ±2.9 days. */
export function fmtError(lang, targetId, e) {
  const m = TARGET_META[targetId];
  return `±${fmtNumber(lang, e * m.scale, m.digits)}${unit(lang, m.diffUnit)}`;
}
